"""Turn lua/coop_core.lua into loader/coop_core_lua.h (one C string, lines joined with spaces).

Full-line comments are dropped. The console runs the result as a single line, so the Lua must not
rely on newlines (no trailing `--` comments after code).
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "lua" / "coop_core.lua").read_text(encoding="utf-8")
parts = []
for line in src.splitlines():
    s = line.strip()
    if not s or s.startswith("--"):
        continue
    if "--" in s:
        sys.exit(f"inline comment not allowed in embedded Lua: {line!r}")
    parts.append(s)
joined = " ".join(parts)
escaped = joined.replace("\\", "\\\\").replace('"', '\\"')
out = root / "loader" / "coop_core_lua.h"
out.write_text("// generated by tools/embed_lua.py from lua/coop_core.lua - do not edit\n"
               f'static const char *kCoreLua = "{escaped}";\n', encoding="utf-8")
print(f"wrote {out} ({len(joined)} chars)")

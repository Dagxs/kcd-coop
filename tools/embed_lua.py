"""Turn lua/coop_core.lua into loader/coop_core_lua.h.

The file is split into top-level blocks at blank lines, packed into chunks of at most MAX chars, and each
chunk is wrapped in `if (CoopCoreVersion or 0) < VERSION then ... end` (VERSION read from the file).
Full-line comments are dropped and lines are joined with spaces, so no trailing `--` comments.
"""
import pathlib
import re
import sys

MAX = 1800
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "lua" / "coop_core.lua").read_text(encoding="utf-8")
m = re.search(r"^CoopCoreVersion = (\d+)$", src, re.M)
if not m:
    sys.exit("coop_core.lua must set CoopCoreVersion = N")
version = int(m.group(1))

blocks, cur = [], []
for line in src.splitlines():
    s = line.strip()
    if s.startswith("--"):
        continue
    if "--" in s:
        sys.exit(f"inline comment not allowed in embedded Lua: {line!r}")
    if not s:
        if cur and not line.startswith(" "):
            blocks.append(" ".join(cur))
            cur = []
        continue
    cur.append(s)
if cur:
    blocks.append(" ".join(cur))

guard = f"if (CoopCoreVersion or 0) < {version} then "
chunks, acc = [], ""
for b in blocks:
    if len(b) + len(guard) + 5 > MAX:
        sys.exit(f"block too long for one chunk ({len(b)} chars): {b[:60]}...")
    if acc and len(guard) + len(acc) + 1 + len(b) + 4 > MAX:
        chunks.append(acc)
        acc = ""
    acc = (acc + " " + b).strip()
if acc:
    chunks.append(acc)

def c_str(t):
    return '"' + t.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = root / "loader" / "coop_core_lua.h"
body = ",\n    ".join(c_str(guard + c + " end") for c in chunks)
out.write_text("// generated by tools/embed_lua.py from lua/coop_core.lua - do not edit\n"
               f"static const char *kCoreLua[] = {{\n    {body}\n}};\n"
               f"#define CORE_LUA_CHUNKS {len(chunks)}\n", encoding="utf-8")
print(f"wrote {out}: {len(chunks)} chunks, sizes {[len(c) for c in chunks]}")
